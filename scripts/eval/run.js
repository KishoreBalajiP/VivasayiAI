import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Runs every evaluation that can run without credentials and writes the results.
//   npm run eval -- --date=2026-10-16
// Output: docs/research/evaluation/results/<name>.json and results/SUMMARY.md. Nothing here calls a live
// provider; anything that needs one is listed as pending in its own result and in the summary.

process.env.GOOGLE_API_KEY ||= "eval-placeholder";
process.env.COHERE_API_KEY ||= "eval-placeholder";
process.env.CHROMA_API_KEY ||= "eval-placeholder";
process.env.CHROMA_TENANT ||= "eval-placeholder";
process.env.CHROMA_DATABASE ||= "eval-placeholder";
process.env.SESSION_JWT_SECRET ||= "eval-secret-0123456789abcdef";
process.env.LOG_LEVEL ||= "silent";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const outDir = join(root, "docs", "research", "evaluation", "results");
const dateArg = process.argv.find((arg) => arg.startsWith("--date="));
const date = dateArg ? dateArg.slice(7) : null;

const git = (command) => {
  try { return execSync(command, { cwd: root, stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); } catch { return null; }
};

const pct = (r) => (r && r.value !== null ? `${(r.value * 100).toFixed(1)}% (${r.k}/${r.n})` : "n/a");

const main = async () => {
  mkdirSync(outDir, { recursive: true });
  const { runGeometryEvaluation } = await import("./geometry.eval.js");
  const { runNameEvaluation } = await import("./names.eval.js");
  const { runFusionEvaluation } = await import("./fusion.eval.js");
  const { runSatelliteSimulation } = await import("./satellite.sim.eval.js");
  const { runChatContextEvaluation } = await import("./chatContext.eval.js");

  const environment = {
    date, node: process.version, platform: `${process.platform}-${process.arch}`,
    commit: git("git rev-parse --short HEAD"), branch: git("git rev-parse --abbrev-ref HEAD"), dirty: Boolean(git("git status --porcelain")),
  };
  const results = {
    geometry: runGeometryEvaluation(),
    names: runNameEvaluation(),
    fusion: runFusionEvaluation(),
    satelliteSimulation: runSatelliteSimulation(),
    chatContext: await runChatContextEvaluation(),
  };
  for (const [name, result] of Object.entries(results)) {
    writeFileSync(join(outDir, `${name}.json`), `${JSON.stringify({ environment, ...result }, null, 2)}\n`);
  }

  const g = results.geometry;
  const f = results.fusion.policies;
  const c = results.chatContext;
  const s = results.satelliteSimulation.headline;
  const lines = [
    "# Evaluation summary",
    "",
    `Generated by \`npm run eval\`${date ? ` on ${date}` : ""} at commit ${environment.commit || "unknown"}${environment.dirty ? " (working tree had uncommitted changes)" : ""}. Node ${environment.node}.`,
    "",
    "Every number below comes from a deterministic benchmark on **synthetic or author-labelled data**. None is a measurement on real claims, real documents or real satellite imagery. See each result's `groundTruth` and `limitations`.",
    "",
    "## Geometry (analytic ground truth)",
    `- Containment, outside-parcel detection: precision ${g.containment.scores.precision}, recall ${g.containment.scores.recall} (n=${g.containment.scores.n})`,
    `- Cross-farmer overlap review flag: precision ${g.overlap.flagScores.precision}, recall ${g.overlap.flagScores.recall} (n=${g.overlap.flagScores.n})`,
    `- Invalid-geometry detection: recall ${g.invalidGeometry.detection.recall}, valid polygons wrongly rejected ${pct(g.invalidGeometry.validRejected)}`,
    `- Area: server acres differ from an ellipsoidal reference by a median ${(g.area.relativeError.p50 * 100).toFixed(2)}% (systematic: the server uses the equatorial radius)`,
    "",
    "## Evidence fusion (design-rule conformance, 192 scenarios)",
    ...Object.entries(f).map(([label, v]) => `- ${label}: invalid approvals ${v.invalidApprovalRate.k}/${v.invalidApprovalRate.n}, rejected on AI reading alone ${v.adverseOnAiAlone.k}/${v.adverseOnAiAlone.n}, held for review ${v.heldForReview}`),
    "",
    "## Chat follow-up decisions (specification-scored)",
    `- Intent classification accuracy: ${pct(c.intent.accuracy)}`,
    `- Unnecessary follow-ups: previous rule ${pct(c.followUp.previousRule.unnecessaryFollowUpRate)}, new logic ${pct(c.followUp.newLogic.unnecessaryFollowUpRate)}`,
    `- Necessary follow-ups missed: previous rule ${pct(c.followUp.previousRule.missedNecessaryFollowUpRate)}, new logic ${pct(c.followUp.newLogic.missedNecessaryFollowUpRate)}`,
    `- Crop silently assumed when ambiguous: previous rule ${pct(c.followUp.previousRule.silentAssumptionWhenAmbiguous)}, new logic ${pct(c.followUp.newLogic.silentAssumptionWhenAmbiguous)}`,
    `- Context assembly latency p50/p95: ${c.latencyMs.p50} / ${c.latencyMs.p95} ms (weather stubbed)`,
    "",
    "## Name matching (author-labelled, 60 pairs)",
    `- Accuracy ${pct(results.names.accuracy)}. Tuned on this same set after seeing 5 failures, so optimistic; see names.json tuningHistory.`,
    "",
    "## Satellite threshold simulation (no real imagery)",
    `- False support at no change, clear sky: ${pct(s.falseSupportAtNoChangeClearSky)}; cloudy: ${pct(s.falseSupportAtNoChangeCloudy)}`,
    `- Detection of a 0.15 NDVI drop, clear sky: ${pct(s.detectionAtDrop015ClearSky)}; of a 0.30 drop: ${pct(s.detectionAtDrop030ClearSky)}`,
    `- Inconclusive when 70% of post-event pixels are masked: ${pct(s.inconclusiveWhenMostlyMasked)}`,
    "",
    "## Pending (needs credentials, labelled data or people)",
    "- Answer relevance, groundedness and citation correctness of the live assistant (Gemini key and expert-rated answers).",
    "- Land-document field extraction accuracy (labelled document images and a Gemini key; scorer: scripts/eval/docExtraction.score.js).",
    "- Real satellite acquisition success, cloud rate and damage agreement (Copernicus credentials and independently labelled events).",
    "- Duplicate/overlap performance and ownership-mismatch detection on real cadastral data (authorised official records).",
    "- User study of unnecessary-question experience.",
    "",
  ];
  writeFileSync(join(outDir, "SUMMARY.md"), `${lines.join("\n")}\n`);
  console.log(lines.join("\n"));
};

main().then(() => process.exit(0)).catch((error) => { console.error(error); process.exit(1); });
